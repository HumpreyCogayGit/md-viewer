// Generates THIRD_PARTY_NOTICES.md from the production dependency tree (npm ls --omit=dev).
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const tree = JSON.parse(
  execSync('npm ls --omit=dev --all --json --long', { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }),
);
const packages = new Map();
const walk = (deps = {}) => {
  for (const [name, info] of Object.entries(deps)) {
    if (!info.version || packages.has(`${name}@${info.version}`)) continue;
    const dir = info.path || join(root, 'node_modules', name);
    let license = 'UNKNOWN';
    let repository = '';
    if (existsSync(join(dir, 'package.json'))) {
      const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
      license =
        typeof pkg.license === 'string'
          ? pkg.license
          : pkg.license?.type || (pkg.licenses || []).map((l) => l.type).join(' OR ') || 'UNKNOWN';
      if (license === 'UNKNOWN') {
        const file = ['LICENSE', 'license', 'LICENSE.md', 'LICENSE.txt', 'license.md']
          .map((f) => join(dir, f))
          .find(existsSync);
        const head = file ? readFileSync(file, 'utf8').slice(0, 200) : '';
        if (/MIT License/i.test(head)) license = 'MIT (from LICENSE file)';
        else if (/ISC License/i.test(head)) license = 'ISC (from LICENSE file)';
      }
      repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url || pkg.homepage || '';
    }
    packages.set(`${name}@${info.version}`, {
      name,
      version: info.version,
      license,
      repository: repository.replace(/^git\+/, '').replace(/\.git$/, ''),
    });
    walk(info.dependencies);
  }
};
walk(tree.dependencies);

const rows = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
const byLicense = rows.reduce((map, row) => map.set(row.license, (map.get(row.license) || 0) + 1), new Map());
const summary = [...byLicense]
  .sort((a, b) => b[1] - a[1])
  .map(([license, count]) => `| ${license} | ${count} |`)
  .join('\n');
const table = rows.map((row) => `| ${row.name} | ${row.version} | ${row.license} | ${row.repository} |`).join('\n');
writeFileSync(
  join(root, 'THIRD_PARTY_NOTICES.md'),
  `# Third-Party Notices

Speculo is distributed under the GNU General Public License v3 (see \`LICENSE\`). The production build bundles the
open-source packages listed below. Each package remains under its own license; full license texts are in each
package's distribution (\`node_modules/<name>/LICENSE*\`) and repository.

Generated by \`npm run notices\` from \`npm ls --omit=dev\`. Regenerate after changing dependencies.

## License summary

| License | Packages |
| --- | --- |
${summary}

All licenses above are permissive or offer a GPLv3-compatible choice, so they are compatible with distribution under
GPLv3:

- DOMPurify (MPL-2.0 OR Apache-2.0) is used under Apache-2.0.
- elkjs (EPL-2.0 OR GPL-3.0-or-later, a Mermaid dependency) is used under GPL-3.0-or-later.
- BlueOak-1.0.0 (glob/minimatch family) is a permissive license. Fonts (Assistant, Caveat via \`@fontsource\`) are
under the SIL Open Font License 1.1.

No source code from CyberChef (Apache-2.0, Crown Copyright) is included; operations are independent implementations.

## Packages

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table}
`,
);
console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages).`);
console.log(summary);
